import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { z } from "zod";

import { MCP_SERVER_NAME, mcpServerUrl } from "./mcp-server.js";

// OpenCode auto-loads every file in `<config dir>/plugin/`, so telemetry is one file.
// The user's `opencode.json` gets only the MCP server entry, which a plugin cannot
// add for `opencode mcp auth`. OpenCode's own `experimental.openTelemetry` is
// not used: its spans carry the prompt and response verbatim, and no cost or
// repository.

export const OPENCODE_PLUGIN_FILENAME = "clocktopus.js";

/** The line `readOpencodePlugin` parses back out of the plugin. */
const CONFIG_MARKER = "const CLOCKTOPUS = ";

const VERSION_MARKER = "// clocktopus-plugin-version: ";

// Bump whenever `buildOpencodePlugin` changes what it emits: the generated plugin does
// not follow CLI upgrades, and `agent doctor` compares this against the file's stamp.
export const OPENCODE_PLUGIN_VERSION = 2;

export function opencodeConfigDir(): string {
  if (process.env.OPENCODE_CONFIG_DIR) return process.env.OPENCODE_CONFIG_DIR;
  if (process.env.XDG_CONFIG_HOME)
    return join(process.env.XDG_CONFIG_HOME, "opencode");
  return join(homedir(), ".config", "opencode");
}

export function opencodePluginPath(): string {
  return join(opencodeConfigDir(), "plugin", OPENCODE_PLUGIN_FILENAME);
}

export type OpencodePluginConfig = {
  endpoint: string;
  token: string;
  // Argv rather than a command line, because the plugin spawns it without a shell.
  hookArgv: string[];
};

// Handles only the quoting `resolveHookCommand` produces: double quotes around
// whitespace.
export function splitCommandLine(command: string): string[] {
  return (command.match(/"[^"]*"|\S+/g) ?? []).map((part) =>
    part.startsWith('"') && part.endsWith('"') ? part.slice(1, -1) : part,
  );
}

// OpenCode 1 loads a plugin's named function exports; OpenCode 2 loads only a default
// export `{ id, setup }`, and refuses the other shape.
export type OpencodePluginApi = 1 | 2;

const API_MARKER = "// opencode-plugin-api: ";

// Null when the version is unknown, which `agent setup` writes for as the current API.
export function opencodePluginApiFor(
  opencodeVersion: string | null,
): OpencodePluginApi | null {
  const major = Number.parseInt(opencodeVersion ?? "", 10);
  if (!Number.isFinite(major)) return null;
  return major >= 2 ? 2 : 1;
}

// Generated rather than shipped because OpenCode gives a plugin no way to read our
// environment, so the token is baked into the file.
export function buildOpencodePlugin(
  config: OpencodePluginConfig,
  api: OpencodePluginApi = 2,
): string {
  return `// Generated by 'clocktopus agent setup'. Edits will be overwritten.
${VERSION_MARKER}${OPENCODE_PLUGIN_VERSION}
${API_MARKER}${api}
//
// Reports what OpenCode sessions cost to Clocktopus. Two channels, because spend and
// repository context come from different places and neither is much use alone:
//
//   spend    POSTed straight to the receiver as OTel GenAI spans, because it happens
//            per model call and spawning a process each time would be absurd.
//   context  handed to 'clocktopus agent hook', which already resolves git remotes,
//            diffs a session's commit range and sweeps dead sessions.
//
// Nothing a person wrote is read: not the prompt, not the reply, not tool output.
import { spawn } from "node:child_process";

${CONFIG_MARKER}${JSON.stringify(config)};

const REQUEST_TIMEOUT_MS = 4000;

/** ms since epoch -> the nanosecond string OTLP expects. */
const nano = (ms) => \`\${Math.round(ms)}000000\`;

const attr = (key, value) =>
  typeof value === "number"
    ? { key, value: { doubleValue: value } }
    : { key, value: { stringValue: String(value) } };

// usage: { sessionID, started, ended (ms), modelID, providerID, tokens, cost }, with
// tokens as OpenCode reports them: { input, output, reasoning, cache: { read, write } }.
function spans(usage) {
  const shared = [
    attr("gen_ai.client.session_id", usage.sessionID),
    attr("gen_ai.client.name", "opencode"),
  ];

  return [
    {
      // Carries the call's duration and nothing else. Clocktopus takes active time from
      // this span alone, so one per model call is what makes the total "time the agent
      // was working" rather than "time the window was open".
      name: "gen_ai.client.session",
      startTimeUnixNano: nano(usage.started),
      endTimeUnixNano: nano(usage.ended),
      attributes: shared,
    },
    {
      name: "gen_ai.client.generation",
      startTimeUnixNano: nano(usage.started),
      endTimeUnixNano: nano(usage.ended),
      attributes: [
        ...shared,
        attr("gen_ai.request.model", usage.modelID),
        attr("gen_ai.provider.name", usage.providerID),
        // OpenCode reports input already net of the cached prefix, so these buckets add up
        // rather than overlap — the opposite of Codex, which reports input inclusive.
        attr("gen_ai.usage.input_tokens", usage.tokens.input),
        // Reasoning tokens are output tokens that were not shown. OpenCode reports them
        // separately and Clocktopus has no bucket for them, so they are folded in: its own
        // totals treat them this way and it prices them at the output rate, so leaving them
        // out would under-report tokens against a cost that already includes them.
        attr(
          "gen_ai.usage.output_tokens",
          usage.tokens.output + (usage.tokens.reasoning ?? 0),
        ),
        attr("gen_ai.usage.cache_read_input_tokens", usage.tokens.cache.read),
        attr(
          "gen_ai.usage.cache_creation_input_tokens",
          usage.tokens.cache.write,
        ),
        // Priced by OpenCode from the models.dev rate card, so Clocktopus records it as an
        // estimate, never as a settled bill.
        attr("gen_ai.usage.cost", usage.cost),
      ],
    },
  ];
}

async function report(usage, version) {
  const body = {
    resourceSpans: [
      {
        resource: {
          attributes: [
            attr("service.name", "opencode"),
            ...(version ? [attr("service.version", version)] : []),
          ],
        },
        scopeSpans: [
          {
            scope: { name: "clocktopus.opencode", version: "${api}" },
            spans: spans(usage),
          },
        ],
      },
    ],
  };

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);
  try {
    await fetch(\`\${CLOCKTOPUS.endpoint.replace(/\\/$/, "")}/v1/traces\`, {
      method: "POST",
      headers: {
        "content-type": "application/json",
        authorization: \`Bearer \${CLOCKTOPUS.token}\`,
      },
      body: JSON.stringify(body),
      signal: controller.signal,
    });
  } catch {
    // Telemetry must never break the session it measures.
  } finally {
    clearTimeout(timer);
  }
}

/** Hands a session event to the CLI, which owns all the git logic. */
function notify(event, sessionID, cwd) {
  try {
    const [command, ...args] = CLOCKTOPUS.hookArgv;
    const child = spawn(command, args, {
      detached: true,
      stdio: ["pipe", "ignore", "ignore"],
    });
    child.unref();
    child.stdin.on("error", () => {});
    child.stdin.end(
      JSON.stringify({
        session_id: sessionID,
        hook_event_name: event,
        cwd,
      }),
    );
  } catch {
    // Same contract as everything else here: fail silently.
  }
}

${api === 2 ? OPENCODE_V2_EXPORT : OPENCODE_V1_EXPORT}`;
}

const OPENCODE_V1_EXPORT = `export const ClocktopusPlugin = async ({ directory, worktree }) => {
  const root = worktree || directory;
  let version = null;

  return {
    event: async ({ event }) => {
      if (event.type === "session.created") {
        version = event.properties.info?.version ?? version;
        notify("SessionStart", event.properties.sessionID, root);
        return;
      }

      // OpenCode has no "session ended" event — 'idle' is what it emits when the agent
      // stops and waits for a human. Treating that as the end keeps the session's end time
      // tracking the last moment it was busy, which is the bound commit attribution needs;
      // re-sending on a later turn is harmless, since the receiver merges.
      if (event.type === "session.idle") {
        notify("SessionEnd", event.properties.sessionID, root);
        return;
      }

      if (event.type === "message.updated") {
        const message = event.properties.info;
        // Assistant messages only, and only once finished — an in-flight message is
        // republished on every token, with counts that are not final.
        if (message?.role !== "assistant" || !message.time?.completed) return;
        await report(
          {
            sessionID: message.sessionID,
            started: message.time.created,
            ended: message.time.completed,
            modelID: message.modelID,
            providerID: message.providerID,
            tokens: message.tokens,
            cost: message.cost,
          },
          version,
        );
      }
    },
  };
};
`;

const OPENCODE_V2_EXPORT = `// A turn ends in exactly one of these; none of them carries a location.
const TURN_ENDED = new Set([
  "session.execution.succeeded",
  "session.execution.failed",
  "session.execution.interrupted",
]);

export default {
  id: "clocktopus",
  setup: async ({ app, location, event }) => {
    const version = app?.version ?? null;
    const root = location.directory;
    // OpenCode runs one setup per directory and gives each one every directory's events,
    // so an instance takes a session as its own only from a step run in its directory.
    const sessions = new Set();
    // assistantMessageID -> the session.step.started data, for the model and start time
    // that session.step.ended does not repeat.
    const steps = new Map();

    const handle = (received) => {
      const data = received.data ?? {};

      if (received.type === "session.step.started") {
        if (received.location?.directory !== root) return;
        if (!sessions.has(data.sessionID)) {
          sessions.add(data.sessionID);
          notify("SessionStart", data.sessionID, root);
        }
        steps.set(data.assistantMessageID, data);
        return;
      }

      if (
        received.type === "session.step.ended" ||
        received.type === "session.step.failed"
      ) {
        const step = steps.get(data.assistantMessageID);
        if (!step) return;
        steps.delete(data.assistantMessageID);
        // A failed step carries usage only when the provider billed for it.
        if (!data.tokens) return;
        void report(
          {
            sessionID: data.sessionID,
            started: step.started,
            ended: received.created,
            modelID: step.model.id,
            providerID: step.model.providerID,
            tokens: data.tokens,
            cost: data.cost ?? 0,
          },
          version,
        );
        return;
      }

      // The end of a turn stands in for the end of the session, which OpenCode never
      // signals; re-sending on a later turn is harmless, since the receiver merges.
      if (TURN_ENDED.has(received.type) && sessions.has(data.sessionID)) {
        notify("SessionEnd", data.sessionID, root);
      }
    };

    // Not awaited: setup has to return for OpenCode to finish loading plugins.
    void (async () => {
      try {
        for await (const received of event.subscribe()) {
          try {
            handle(received);
          } catch {
            // One malformed event must not end the subscription.
          }
        }
      } catch {
        // Telemetry must never break the session it measures.
      }
    })();
  },
};
`;

export function readOpencodePlugin(path = opencodePluginPath()): {
  path: string;
  exists: boolean;
  modifiedAt: Date | null;
  config: OpencodePluginConfig | null;
  // Null when the file carries no stamp, which callers treat as stale.
  version: number | null;
  // 1 when the file carries no API stamp: only OpenCode 1 plugins were written without one.
  api: OpencodePluginApi;
} {
  if (!existsSync(path)) {
    return {
      path,
      exists: false,
      modifiedAt: null,
      config: null,
      version: null,
      api: 1,
    };
  }

  const modifiedAt = statSync(path).mtime;
  let config: OpencodePluginConfig | null = null;
  let version: number | null = null;
  let api: OpencodePluginApi = 1;

  try {
    const lines = readFileSync(path, "utf8").split("\n");

    const stamp = lines.find((candidate) =>
      candidate.startsWith(VERSION_MARKER),
    );
    if (stamp) {
      const parsedVersion = Number.parseInt(
        stamp.slice(VERSION_MARKER.length).trim(),
        10,
      );
      if (Number.isFinite(parsedVersion)) version = parsedVersion;
    }

    if (lines.includes(`${API_MARKER}2`)) api = 2;

    const line = lines.find((candidate) => candidate.startsWith(CONFIG_MARKER));

    if (line) {
      const parsed: unknown = JSON.parse(
        line.slice(CONFIG_MARKER.length).replace(/;\s*$/, ""),
      );
      if (
        parsed &&
        typeof parsed === "object" &&
        typeof (parsed as OpencodePluginConfig).token === "string" &&
        typeof (parsed as OpencodePluginConfig).endpoint === "string" &&
        Array.isArray((parsed as OpencodePluginConfig).hookArgv)
      ) {
        config = parsed as OpencodePluginConfig;
      }
    }
  } catch {
    // Unreadable reports as unconfigured, which sends the user to `setup`.
  }

  return { path, exists: true, modifiedAt, config, version, api };
}

export function writeOpencodePlugin(
  source: string,
  path = opencodePluginPath(),
): { backupPath: string | null } {
  mkdirSync(dirname(path), { recursive: true });

  let backupPath: string | null = null;
  if (existsSync(path)) {
    backupPath = `${path}.clocktopus-backup`;
    copyFileSync(path, backupPath);
  }

  // Rename rather than write in place: OpenCode loads every file here at startup, and
  // a half-written one breaks its plugin system.
  const temporaryPath = `${path}.clocktopus-tmp`;
  writeFileSync(temporaryPath, source, { encoding: "utf8", mode: 0o600 });
  renameSync(temporaryPath, path);

  return { backupPath };
}

export function removeOpencodePlugin(path = opencodePluginPath()): boolean {
  if (!existsSync(path)) return false;
  rmSync(path, { force: true });
  return true;
}

// OpenCode reads `opencode.jsonc` as well; one with comments is refused rather than
// rewritten without them.
export function opencodeConfigPath(): string {
  const dir = opencodeConfigDir();
  const jsonc = join(dir, "opencode.jsonc");
  return existsSync(jsonc) && !existsSync(join(dir, "opencode.json"))
    ? jsonc
    : join(dir, "opencode.json");
}

const OpencodeConfigSchema = z.looseObject({
  mcp: z.record(z.string(), z.unknown()).optional(),
});

export function readOpencodeConfig(path = opencodeConfigPath()) {
  if (!existsSync(path)) {
    return { path, exists: false, config: OpencodeConfigSchema.parse({}) };
  }
  const raw = readFileSync(path, "utf8");
  try {
    return {
      path,
      exists: true,
      config: OpencodeConfigSchema.parse(raw.trim() ? JSON.parse(raw) : {}),
    };
  } catch (error) {
    throw new Error(
      `${path} could not be read as JSON (${
        error instanceof Error ? error.message : "unknown error"
      }). Add the Clocktopus MCP server to it by hand: "mcp": { "${MCP_SERVER_NAME}": { "type": "remote", "url": "<api>/api/mcp", "oauth": {} } }`,
    );
  }
}

type OpencodeConfig = z.infer<typeof OpencodeConfigSchema>;

// OpenCode 1 keys servers directly under `mcp`. OpenCode 2 keys them under
// `mcp.servers` and still loads the v1 shape, merging both and reporting a
// conflict when the two disagree.
function opencodeMcpEntries(config: OpencodeConfig) {
  const servers = z
    .record(z.string(), z.unknown())
    .safeParse(config.mcp?.servers);
  return {
    v1: config.mcp?.[MCP_SERVER_NAME],
    v2: servers.success ? servers.data[MCP_SERVER_NAME] : undefined,
    servers: servers.success ? servers.data : undefined,
  };
}

export function opencodeMcpKey(api: OpencodePluginApi): string {
  return api === 2
    ? `mcp.servers.${MCP_SERVER_NAME}`
    : `mcp.${MCP_SERVER_NAME}`;
}

export function readOpencodeMcpUrl(
  config: OpencodeConfig,
  api: OpencodePluginApi,
): string | null {
  const entries = opencodeMcpEntries(config);
  const entry = z
    .object({ url: z.string() })
    .safeParse(api === 2 ? (entries.v2 ?? entries.v1) : entries.v1);
  return entry.success ? entry.data.url : null;
}

// Drops the entry from both shapes, then `mcp.servers` and `mcp` once empty.
function withoutOpencodeMcp(config: OpencodeConfig) {
  const { servers } = opencodeMcpEntries(config);
  const mcp: Record<string, unknown> = { ...config.mcp };
  delete mcp[MCP_SERVER_NAME];
  if (servers) {
    const rest = { ...servers };
    delete rest[MCP_SERVER_NAME];
    if (Object.keys(rest).length > 0) mcp.servers = rest;
    else delete mcp.servers;
  }
  // `undefined` drops the key from the written JSON.
  return { ...config, mcp: Object.keys(mcp).length > 0 ? mcp : undefined };
}

// `oauth: {}` has OpenCode register itself with the server, the way
// `opencode mcp auth clocktopus` signs in. The entry leaves the other version's
// shape, so OpenCode 2 never loads two copies.
export function applyOpencodeMcp(
  config: OpencodeConfig,
  input: { apiUrl: string; api: OpencodePluginApi },
) {
  const next = withoutOpencodeMcp(config);
  const entry = {
    type: "remote",
    url: mcpServerUrl(input.apiUrl),
    oauth: {},
  };
  if (input.api === 1) {
    return { ...next, mcp: { ...next.mcp, [MCP_SERVER_NAME]: entry } };
  }
  const { servers } = opencodeMcpEntries(next);
  return {
    ...next,
    mcp: { ...next.mcp, servers: { ...servers, [MCP_SERVER_NAME]: entry } },
  };
}

export function removeOpencodeMcp(config: OpencodeConfig) {
  const entries = opencodeMcpEntries(config);
  const removed = [
    ...(entries.v1 === undefined ? [] : [opencodeMcpKey(1)]),
    ...(entries.v2 === undefined ? [] : [opencodeMcpKey(2)]),
  ];
  return {
    config: removed.length > 0 ? withoutOpencodeMcp(config) : config,
    removed,
  };
}

export function writeOpencodeConfig(
  config: OpencodeConfig,
  path = opencodeConfigPath(),
): { backupPath: string | null } {
  mkdirSync(dirname(path), { recursive: true });

  let backupPath: string | null = null;
  if (existsSync(path)) {
    backupPath = `${path}.clocktopus-backup`;
    copyFileSync(path, backupPath);
  }

  const temporaryPath = `${path}.clocktopus-tmp`;
  writeFileSync(temporaryPath, `${JSON.stringify(config, null, 2)}\n`, "utf8");
  renameSync(temporaryPath, path);

  return { backupPath };
}
